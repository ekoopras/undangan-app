<script>
    // Fungsi Manual saat Tombol Menu diklik langsung
    function setActiveMenu(element) {
        element.scrollIntoView({
            behavior: 'smooth',
            block: 'nearest',
            inline: 'center'
        });

        updateNavStyles(element);
    }

    // Fungsi Pembantu untuk mengolah penukaran class CSS secara halus
    function updateNavStyles(activeLink) {
        const links = document.querySelectorAll('.nav-link');
        links.forEach(link => {
            link.classList.remove('text-amber-300', 'font-semibold');
            link.classList.add('text-white/60');
        });

        activeLink.classList.remove('text-white/60');
        activeLink.classList.add('text-amber-300', 'font-semibold');
    }

    // --- OTOMATISASI SCROLL MONITORING ---
    document.addEventListener("DOMContentLoaded", function() {
        // Ambil semua target section berdasarkan atribut href yang ada di menu nav
        const sections = document.querySelectorAll("section[id]");

        const observerOptions = {
            root: null,
            // Pemicu aktif saat section mendominasi 60% layar viewport smartphone
            threshold: 0.6
        };

        const navObserver = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    const id = entry.target.getAttribute("id");
                    const matchingLink = document.querySelector(`.nav-link[href="#${id}"]`);

                    if (matchingLink) {
                        // Jalankan pembaruan gaya warna text emas
                        updateNavStyles(matchingLink);

                        // Buat item menu di dalam navbar ikut bergeser ke tengah otomatis secara halus
                        matchingLink.scrollIntoView({
                            behavior: 'smooth',
                            block: 'nearest',
                            inline: 'center'
                        });
                    }
                }
            });
        }, observerOptions);

        // Mulai mendaftarkan pengawasan ke seluruh elemen section
        sections.forEach(section => navObserver.observe(section));
    });
</script>